-- Every LMS and SMS call. Insert only, written asynchronously.
-- Replaces the legacy goldLogDetails table.
--
-- Request and response bodies are stored in full because reconciliation and dispute
-- handling need the exact payload. This is the right home for them: the grant and the
-- retention here are yours to set, unlike a log aggregator's.
--
--   GRANT INSERT, SELECT ON LMS_API_LOG TO PAYMENT_APP;
--
-- Interval partitioning is not optional. With CLOBs and up to four calls per posting
-- attempt this becomes the largest table in the schema, and a retention purge without
-- partitions is a very expensive DELETE rather than a DROP PARTITION.
--
-- SMS rows never contain the OTP: the endpoint and response have the code and mobile
-- number redacted before the row is written.

CREATE TABLE LMS_API_LOG (
    ID               NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CORRELATION_ID   VARCHAR2(36)  NOT NULL,
    -- Present for posting-flow calls, null for authentication lookups.
    TXN_REFERENCE    VARCHAR2(40),
    ATTEMPT_NO       NUMBER(5),
    -- STATUS_CHECK | AGREEMENT_FETCH | OTS_AMOUNT | POST_TXN | LMS_TOKEN | SMS_TOKEN | SMS_SEND
    API_NAME         VARCHAR2(32)  NOT NULL,
    ENDPOINT         VARCHAR2(512) NOT NULL,
    HTTP_METHOD      VARCHAR2(8)   NOT NULL,
    AGREEMENT_NUMBER VARCHAR2(50),
    REQUEST_BODY     CLOB,
    RESPONSE_BODY    CLOB,
    HTTP_STATUS      NUMBER(5),
    UPSTREAM_STATUS  VARCHAR2(64),
    UPSTREAM_CODE    VARCHAR2(32),
    OUTCOME          VARCHAR2(16)  NOT NULL,
    ERROR_DETAIL     VARCHAR2(512),
    DURATION_MS      NUMBER(19),
    REQUESTED_AT     TIMESTAMP     NOT NULL,
    RESPONDED_AT     TIMESTAMP
)
PARTITION BY RANGE (REQUESTED_AT)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(PARTITION P_INITIAL VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00'));

CREATE INDEX IX_LOG_TXN  ON LMS_API_LOG (TXN_REFERENCE, REQUESTED_AT) LOCAL;
CREATE INDEX IX_LOG_CORR ON LMS_API_LOG (CORRELATION_ID) LOCAL;
CREATE INDEX IX_LOG_API  ON LMS_API_LOG (API_NAME, REQUESTED_AT) LOCAL;
CREATE INDEX IX_LOG_AGMT ON LMS_API_LOG (AGREEMENT_NUMBER, REQUESTED_AT) LOCAL;
